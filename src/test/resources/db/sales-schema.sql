-- Schema for the sales-db test database (H2). Created by the test harness, see TestDatabase.
CREATE TABLE IF NOT EXISTS CUSTOMER (
    ID      BIGINT PRIMARY KEY,
    NAME    VARCHAR(100) NOT NULL,
    REGION  VARCHAR(20)  NOT NULL,
    EMAIL   VARCHAR(100),
    CREDIT_LIMIT NUMERIC(20,4),         -- more digits than a double holds exactly
    VERSION INT DEFAULT 1 NOT NULL      -- optimistic lock version
);
CREATE TABLE IF NOT EXISTS PRODUCT (
    ID       BIGINT PRIMARY KEY,
    NAME     VARCHAR(100) NOT NULL,
    CATEGORY VARCHAR(50)  NOT NULL,
    PRICE    DECIMAL(10,2) NOT NULL,
    WEIGHT_KG DOUBLE PRECISION,         -- approximate value
    VERSION INT DEFAULT 1 NOT NULL      -- optimistic lock version
);
CREATE TABLE IF NOT EXISTS ORDERS (
    ID          BIGINT PRIMARY KEY,
    CUSTOMER_ID BIGINT NOT NULL REFERENCES CUSTOMER(ID),
    ORDER_DATE  DATE NOT NULL,
    STATUS      VARCHAR(20) NOT NULL,
    TOTAL       DECIMAL(12,2) NOT NULL,
    CREATED_AT  TIMESTAMP NOT NULL,     -- no time zone: as stored
    SHIPPED_AT  TIMESTAMP WITH TIME ZONE,
    VERSION     INT DEFAULT 1 NOT NULL  -- optimistic lock version; also covers the order's lines
);
-- No version column: a line is locked through its order (changing a line increments ORDERS.VERSION).
CREATE TABLE IF NOT EXISTS ORDER_LINE (
    ID         BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    ORDER_ID   BIGINT NOT NULL REFERENCES ORDERS(ID),
    PRODUCT_ID BIGINT NOT NULL REFERENCES PRODUCT(ID),
    QUANTITY   INT NOT NULL,
    PRICE      DECIMAL(10,2) NOT NULL
);

-- Read-only account the MCP server connects with (requirements 5.0: the server can read only what this
-- account can read).
CREATE USER IF NOT EXISTS MCP_READER PASSWORD 'reader';
GRANT SELECT ON CUSTOMER, PRODUCT, ORDERS, ORDER_LINE TO MCP_READER;

-- Account for a server with write operations (samples/order-desk): it can read everything, and change only
-- what that server's write operations change.
CREATE USER IF NOT EXISTS MCP_ORDER_DESK PASSWORD 'orderdesk';
GRANT SELECT ON CUSTOMER, PRODUCT, ORDERS, ORDER_LINE TO MCP_ORDER_DESK;
GRANT UPDATE ON CUSTOMER, PRODUCT, ORDERS TO MCP_ORDER_DESK;
GRANT INSERT, UPDATE, DELETE ON ORDER_LINE TO MCP_ORDER_DESK;
