-- Schema for the sales-db test database (H2). Created by the test harness, see TestDatabase.
CREATE TABLE IF NOT EXISTS CUSTOMER (
    ID      BIGINT PRIMARY KEY,
    NAME    VARCHAR(100) NOT NULL,
    REGION  VARCHAR(20)  NOT NULL,
    EMAIL   VARCHAR(100)
);
CREATE TABLE IF NOT EXISTS PRODUCT (
    ID       BIGINT PRIMARY KEY,
    NAME     VARCHAR(100) NOT NULL,
    CATEGORY VARCHAR(50)  NOT NULL,
    PRICE    DECIMAL(10,2) NOT NULL
);
CREATE TABLE IF NOT EXISTS ORDERS (
    ID          BIGINT PRIMARY KEY,
    CUSTOMER_ID BIGINT NOT NULL REFERENCES CUSTOMER(ID),
    ORDER_DATE  DATE NOT NULL,
    STATUS      VARCHAR(20) NOT NULL,
    TOTAL       DECIMAL(12,2) NOT NULL
);
CREATE TABLE IF NOT EXISTS ORDER_LINE (
    ID         BIGINT PRIMARY KEY,
    ORDER_ID   BIGINT NOT NULL REFERENCES ORDERS(ID),
    PRODUCT_ID BIGINT NOT NULL REFERENCES PRODUCT(ID),
    QUANTITY   INT NOT NULL,
    PRICE      DECIMAL(10,2) NOT NULL
);

-- Read-only account the MCP server connects with (requirements 5.0: the server can read only what this
-- account can read).
CREATE USER IF NOT EXISTS MCP_READER PASSWORD 'reader';
GRANT SELECT ON CUSTOMER, PRODUCT, ORDERS, ORDER_LINE TO MCP_READER;
